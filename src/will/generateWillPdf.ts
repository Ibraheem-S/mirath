/**
 * Generates a formal, print-ready Last Will & Testament (Wasiyya) PDF from a
 * completed faraid calculation. Client-side, exact — the same fractions the
 * engine computed are what appear in the document.
 */
import { jsPDF } from "jspdf";
import type { CalcResult, EstateInput, FamilyInput } from "@/engine";
import { fmt, fmtPct, frac } from "@/engine";

export interface WillMeta {
  testatorName: string;
  city: string;
  date: string;
  executorName: string;
  bequestRecipient: string;
}

export const emptyWillMeta: WillMeta = {
  testatorName: "",
  city: "",
  date: new Date().toISOString().slice(0, 10),
  executorName: "",
  bequestRecipient: "",
};

const INK: [number, number, number] = [33, 29, 22];
const GREEN: [number, number, number] = [29, 74, 56];
const GOLD: [number, number, number] = [176, 141, 46];
const SOFT: [number, number, number] = [92, 85, 69];

const money = (v: number, currency: string) =>
  new Intl.NumberFormat(undefined, { style: "currency", currency, maximumFractionDigits: 2 }).format(v);

/** jsPDF's built-in Times covers Latin-1 only — normalize typography to safe glyphs. */
function sanitize(text: string): string {
  return text
    .replace(/ﷺ/g, "(peace be upon him)")
    .replace(/[−–—]/g, "-")
    .replace(/⇒/g, "=>")
    .replace(/[’‘]/g, "'")
    .replace(/•/g, "-")
    .replace(/[“”]/g, '"')
    .replace(/…/g, "...")
    .replace(/[^\x20-\x7E\xC0-\xFF]/g, "");
}

const MADHHAB_NAME: Record<string, string> = {
  hanafi: "Hanafi",
  maliki: "Maliki",
  shafii: "Shafi'i",
  hanbali: "Hanbali",
};

export function generateWillPdf(
  result: CalcResult,
  family: FamilyInput,
  estate: EstateInput,
  meta: WillMeta,
): void {
  const doc = new jsPDF({ unit: "pt", format: "letter" });
  const W = 612;
  const M = 64; // margin
  const CW = W - 2 * M; // content width
  let y = 0;

  const newPage = () => {
    doc.addPage();
    y = M;
    footer();
  };
  const footer = () => {
    const page = doc.getNumberOfPages();
    doc.setFont("times", "italic");
    doc.setFontSize(7.5);
    doc.setTextColor(...SOFT);
    doc.text(
      "Generated by Mirath — an educational faraid computation. Not a fatwa; confirm with a qualified scholar and local counsel.",
      M,
      792 - 34,
    );
    doc.text(`Page ${page}`, W - M, 792 - 34, { align: "right" });
    doc.setTextColor(...INK);
  };
  const need = (h: number) => {
    if (y + h > 792 - 56) newPage();
  };
  const para = (text: string, opts: { size?: number; style?: "normal" | "bold" | "italic"; color?: [number, number, number]; gap?: number; indent?: number } = {}) => {
    const size = opts.size ?? 10;
    doc.setFont("times", opts.style ?? "normal");
    doc.setFontSize(size);
    doc.setTextColor(...(opts.color ?? INK));
    const lines = doc.splitTextToSize(sanitize(text), CW - (opts.indent ?? 0));
    const h = lines.length * (size * 1.35);
    need(h + (opts.gap ?? 8));
    doc.text(lines, M + (opts.indent ?? 0), y + size);
    y += h + (opts.gap ?? 8);
  };
  const heading = (text: string, sub?: string) => {
    need(56);
    y += 6;
    doc.setDrawColor(...GOLD);
    doc.setLineWidth(1.1);
    doc.line(M, y, M + CW, y);
    y += 16;
    doc.setFont("times", "bold");
    doc.setFontSize(12.5);
    doc.setTextColor(...GREEN);
    doc.text(text, M, y);
    y += 6;
    if (sub) {
      doc.setFont("times", "italic");
      doc.setFontSize(9);
      doc.setTextColor(...SOFT);
      const lines = doc.splitTextToSize(sanitize(sub), CW);
      doc.text(lines, M, y + 8);
      y += lines.length * 11 + 4;
    }
    y += 10;
    doc.setTextColor(...INK);
  };

  // ---------- title page header ----------
  y = M + 8;
  doc.setFont("times", "normal");
  doc.setFontSize(9.5);
  doc.setTextColor(...SOFT);
  doc.text("In the name of Allah, the Most Merciful, the Most Compassionate", W / 2, y, { align: "center" });
  y += 30;
  doc.setFont("times", "bold");
  doc.setFontSize(21);
  doc.setTextColor(...INK);
  doc.text("THE LAST WILL AND TESTAMENT", W / 2, y, { align: "center" });
  y += 20;
  doc.setFont("times", "italic");
  doc.setFontSize(12);
  doc.setTextColor(...GREEN);
  doc.text("(al-Wasiyya — drawn in accordance with the Islamic law of inheritance)", W / 2, y, { align: "center" });
  y += 16;
  doc.setDrawColor(...GOLD);
  doc.setLineWidth(1.4);
  doc.line(W / 2 - 120, y, W / 2 + 120, y);
  y += 26;
  doc.setTextColor(...INK);

  const name = meta.testatorName.trim() || "________________________";
  const city = meta.city.trim() || "________________________";
  const dateStr = meta.date.trim() || "__________";
  const madhhab = MADHHAB_NAME[result.appliedRules.madhhab] ?? result.appliedRules.madhhab;

  // ---------- preamble ----------
  para(
    `I, ${name}, of ${city}, being of sound mind and memory, and bearing witness that there is no god but Allah and that Muhammad is His servant and Messenger, do hereby declare this to be my Last Will and Testament, executed on ${dateStr}.`,
    { size: 10.5 },
  );
  para(
    `I direct that my estate be distributed in accordance with the Holy Quran (Surah an-Nisa, 4:11–12 and 4:176) and the Sunnah of the Prophet Muhammad (peace be upon him), following the positions of the ${madhhab} school of law as itemized in Article IV below. "Allah instructs you concerning your children: for the male, what is equal to the share of two females… after any bequest he may have made or debt." (Quran 4:11)`,
  );

  // ---------- Article I ----------
  const p = result.pipeline!;
  heading("ARTICLE I — FUNERAL EXPENSES AND DEBTS", "First charges upon the estate, by consensus of the four schools.");
  para(
    `I direct my executor to pay, before any distribution to heirs: first, my reasonable funeral and burial expenses (estimated at ${money(p.funeral, p.currency)}); and second, all my lawful debts, including any unpaid zakat (estimated at ${money(p.debts, p.currency)}). My gross estate is estimated at ${money(p.gross, p.currency)}, leaving ${money(p.afterObligations, p.currency)} after these obligations.`,
  );

  // ---------- Article II ----------
  heading("ARTICLE II — THE BEQUEST (AL-WASIYYA)", "Limited by the Sunnah to one third of the estate after debts (Sahih al-Bukhari 2742; Sahih Muslim 1628).");
  if (p.wasiyyaApplied > 0) {
    const recipient = meta.bequestRecipient.trim() || "the beneficiary named in my records";
    para(
      `From the estate remaining after Article I, I bequeath ${money(p.wasiyyaApplied, p.currency)} to ${recipient}. This bequest does not exceed one third of the said remainder (the lawful maximum of ${money(p.wasiyyaAllowedCap, p.currency)}).`,
    );
    if (estate.wasiyyaRecipientIsHeir) {
      para(
        `I note that the said beneficiary is a legal heir. Per the Prophet's declaration "there is no bequest for an heir" (Jami' at-Tirmidhi 2120), this bequest shall take effect only if all my adult heirs freely consent to it after my death; failing such consent it is void and the amount reverts to the residuary estate.`,
        { style: "italic" },
      );
    }
  } else {
    para(
      "I make no bequest beyond the shares ordained by Allah; my entire estate after Article I passes to my heirs as set out in Article III.",
    );
  }

  // ---------- Article III ----------
  heading(
    "ARTICLE III — DISTRIBUTION OF THE RESIDUARY ESTATE (AL-MIRATH)",
    `The net estate of ${money(p.netMirath, p.currency)} is divided as follows, each share being the exact fraction prescribed:`,
  );

  // table header
  const cols = [M, M + 190, M + 258, M + 316, M + 402]; // heir | share | % | amount
  const tableHead = () => {
    need(44);
    doc.setFillColor(230, 235, 221);
    doc.rect(M, y - 10, CW, 18, "F");
    doc.setFont("times", "bold");
    doc.setFontSize(8.5);
    doc.setTextColor(...GREEN);
    doc.text("HEIR", cols[0] + 3, y + 2);
    doc.text("SHARE", cols[1], y + 2);
    doc.text("PORTION", cols[2], y + 2);
    doc.text("AMOUNT", cols[3], y + 2);
    doc.text("LEGAL BASIS", cols[4], y + 2);
    y += 14;
    doc.setTextColor(...INK);
  };
  tableHead();
  for (const a of result.allocations) {
    const f = frac(a.shareTotalNum, a.shareTotalDen);
    const basis = a.evidence[0] ?? "";
    need(30);
    doc.setFont("times", "normal");
    doc.setFontSize(9);
    doc.text(doc.splitTextToSize(sanitize(a.label), 182), cols[0] + 3, y + 8);
    doc.setFont("times", "bold");
    doc.text(a.shareTotalNum === 0 ? "—" : fmt(f), cols[1], y + 8);
    doc.setFont("times", "normal");
    doc.text(a.shareTotalNum === 0 ? "0%" : fmtPct(f), cols[2], y + 8);
    doc.text(money(a.amountTotal, p.currency), cols[3], y + 8);
    doc.setFontSize(7.5);
    doc.setTextColor(...SOFT);
    doc.text(doc.splitTextToSize(sanitize(basis), CW - (cols[4] - M)), cols[4], y + 8);
    doc.setTextColor(...INK);
    y += 16;
    if (a.perHead) {
      doc.setFont("times", "italic");
      doc.setFontSize(8);
      doc.setTextColor(...SOFT);
      doc.text(
        sanitize(
          `each son ${fmt(frac(a.perHead.maleShareNum, a.perHead.maleShareDen))} (${money(a.perHead.maleAmount, p.currency)}); each daughter ${fmt(frac(a.perHead.femaleShareNum, a.perHead.femaleShareDen))} (${money(a.perHead.femaleAmount, p.currency)}) — the male receiving the share of two females (Quran 4:11)`,
        ),
        cols[0] + 12,
        y + 6,
      );
      doc.setTextColor(...INK);
      y += 14;
    }
    doc.setDrawColor(220, 214, 196);
    doc.setLineWidth(0.5);
    doc.line(M, y - 4, M + CW, y - 4);
  }
  // total row
  need(24);
  doc.setFont("times", "bold");
  doc.setFontSize(9);
  doc.text("TOTAL", cols[0] + 3, y + 8);
  doc.text("1", cols[1], y + 8);
  doc.text("100%", cols[2], y + 8);
  doc.text(money(p.netMirath, p.currency), cols[3], y + 8);
  y += 22;

  if (result.awlApplied)
    para("The prescribed shares exceeded the estate; by the ruling of Umar ibn al-Khattab (consensus of the four Sunni schools), every share above has been reduced proportionally ('awl).", { size: 8.5, style: "italic", color: SOFT });
  if (result.raddApplied)
    para("A surplus remained with no residuary heir; it has been returned proportionally to the eligible fixed-share heirs (radd), per the school position stated in Article IV.", { size: 8.5, style: "italic", color: SOFT });
  for (const s of result.specialCases) {
    para(`Named case: ${s}`, { size: 8.5, style: "italic", color: SOFT });
  }
  if (result.exclusions.length > 0) {
    para("The following relatives are excluded (hajb) and receive nothing:", { size: 8.5, style: "bold" });
    for (const e of result.exclusions) {
      para(`•  ${e.label} — blocked by ${e.blocker}. ${e.reason}`, { size: 8.5, indent: 10, gap: 4 });
    }
  }

  // ---------- Article IV ----------
  heading("ARTICLE IV — JURISTIC POSITIONS APPLIED", "Where the schools of law diverge, this will follows the positions below.");
  const r = result.appliedRules;
  para(`School baseline: the ${madhhab} school.`, { size: 9.5, gap: 5 });
  para(
    `•  Grandfather with siblings: ${r.grandfatherWithSiblings === "exclude" ? "the grandfather excludes all siblings (Hanafi — Abu Bakr's position)" : "siblings share beside the grandfather by the muqasama computation (Maliki/Shafi'i/Hanbali — Zayd ibn Thabit's position)"}.`,
    { size: 9.5, gap: 4 },
  );
  para(
    `•  Al-Mushtaraka: ${r.mushtaraka === "share" ? "full brothers join the uterine siblings' third (Maliki/Shafi'i/Hanbali)" : "full brothers receive nothing in that case (Hanafi)"}.`,
    { size: 9.5, gap: 4 },
  );
  para(
    `•  Surplus return (radd): ${r.spouseRadd === "yes" ? "the spouse participates in radd when no blood heir exists (Maliki/Shafi'i/Hanbali)" : "the spouse does not receive radd (classical Hanafi)"}.`,
    { size: 9.5, gap: 4 },
  );
  para(
    `•  No-heir surplus: ${r.dhawuArham === "inherit" ? "passes to distant uterine kin, dhawu'l-arham (Hanafi/Hanbali)" : "passes to the public treasury, bayt al-mal (Maliki/Shafi'i)"}.`,
    { size: 9.5, gap: 4 },
  );

  // ---------- Article V ----------
  heading("ARTICLE V — EXECUTOR");
  const executor = meta.executorName.trim() || "________________________";
  para(
    `I appoint ${executor} as executor of this will, to pay my funeral expenses, debts and bequest in the order of Articles I–II, to distribute the residue exactly as Article III provides, and to seek the guidance of a qualified scholar should any question arise that this document does not resolve.`,
  );

  // ---------- signatures ----------
  heading("SIGNATURES AND WITNESSES", "Signed and declared in the presence of two witnesses.");
  need(120);
  const sigLine = (label: string, x: number) => {
    doc.setDrawColor(...INK);
    doc.setLineWidth(0.8);
    doc.line(x, y, x + 200, y);
    doc.setFont("times", "normal");
    doc.setFontSize(8.5);
    doc.setTextColor(...SOFT);
    doc.text(label, x, y + 12);
    doc.setTextColor(...INK);
  };
  sigLine(`Testator — ${name}`, M);
  sigLine("Date", M + CW - 140);
  y += 52;
  sigLine("Witness 1 — name and signature", M);
  sigLine("Witness 2 — name and signature", M + CW - 220);
  y += 40;

  // ---------- Schedule A ----------
  heading("SCHEDULE A — CALCULATION RECORD", "The complete audit trail of the computation, for review by scholars and executors.");
  result.steps.forEach((s, i) => {
    para(`${String(i + 1).padStart(2, "0")}. ${s.title}. ${s.detail}`, { size: 8.5, gap: 5 });
  });
  para(
    "Family constellation on which this will is based: " + describeFamily(family) + ".",
    { size: 8.5, style: "italic", color: SOFT },
  );

  footer();
  doc.save(`wasiyya-islamic-will-${dateStr}.pdf`);
}

function describeFamily(f: FamilyInput): string {
  const parts: string[] = [];
  const push = (n: number | boolean, singular: string, plural?: string) => {
    const c = typeof n === "boolean" ? (n ? 1 : 0) : n;
    if (c > 0) parts.push(c === 1 ? singular : `${c} ${plural ?? singular + "s"}`);
  };
  push(f.husband, "husband");
  push(f.wives, "wife", "wives");
  push(f.father, "father");
  push(f.mother, "mother");
  push(f.paternalGrandfather, "paternal grandfather");
  push(f.maternalGrandmother, "maternal grandmother");
  push(f.paternalGrandmother, "paternal grandmother");
  push(f.sons, "son");
  push(f.daughters, "daughter");
  push(f.sonsSons, "son's son");
  push(f.sonsDaughters, "son's daughter");
  push(f.fullBrothers, "full brother");
  push(f.fullSisters, "full sister");
  push(f.paternalBrothers, "paternal half-brother");
  push(f.paternalSisters, "paternal half-sister");
  push(f.maternalBrothers, "maternal half-brother");
  push(f.maternalSisters, "maternal half-sister");
  push(f.fullNephews, "full brother's son");
  push(f.paternalNephews, "half-brother's son");
  push(f.fullPaternalUncles, "full paternal uncle");
  push(f.paternalUncles, "paternal half-uncle");
  return parts.length ? parts.join(", ") : "none recorded";
}
